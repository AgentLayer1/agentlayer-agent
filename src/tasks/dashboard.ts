/**
 * Dashboard generator for `projects/TASKS.md`.
 *
 * Queries (`buildSections`) and formatter (`formatDashboard`) are kept
 * separate so each can be tested/replaced independently. `writeDashboard`
 * composes them and persists the file, preserving the human-authored
 * goals block between sentinel markers.
 */
import { FOLDERS } from '@/config';
import { agentDisplayName } from '@/shared/agent-name';
import { shiftDate, todayDate } from '@/shared/date';
import { readText } from '@/shared/text';
import { buildWork } from '@/work/build';
import type { Work, WorkTask } from '@/work/model';
import { closedSince, overdue, priorityRank, stale, withStatus } from '@/work/views';
import { writeFileSync } from 'fs';
import { basename, join } from 'path';
import { issueLabel } from './issue';

// ── Section building ──────────────────────────────────────────────────

export interface DashboardSections {
  active: WorkTask[];
  blocked: WorkTask[];
  overdue: WorkTask[];
  stale: WorkTask[];
  closedRecent: WorkTask[];
}

const byPriorityThenProject = (a: WorkTask, b: WorkTask): number =>
  priorityRank(a.priority) - priorityRank(b.priority) || a.project.localeCompare(b.project);

/** Every section of TASKS.md, read from the work model against `today`. Pure — no I/O. */
export const buildSections = (work: Work, today: string): DashboardSections => ({
  active: withStatus(work, 'active', 'open').toSorted(byPriorityThenProject),
  blocked: withStatus(work, 'blocked').toSorted(byPriorityThenProject),
  overdue: overdue(work, today).toSorted((a, b) => a.due.localeCompare(b.due)),
  stale: stale(work, today).toSorted((a, b) => a.updated.localeCompare(b.updated)),
  closedRecent: closedSince(work, shiftDate(today, -14))
    .toSorted((a, b) => b.closed.localeCompare(a.closed))
    .slice(0, 20)
});

// ── Formatting ────────────────────────────────────────────────────────

const fileSlug = (filePath: string, fallback: string): string => basename(filePath, '.md') || fallback;

const taskLink = (task: WorkTask): string => `[[${fileSlug(task.path, task.id)}|${task.id}]]`;

type MetaField = keyof Pick<
  WorkTask,
  'project' | 'priority' | 'status' | 'due' | 'updated' | 'closed' | 'blockedBy' | 'dependsOn' | 'assignee'
>;

// TASKS.md names each field as the task file's frontmatter does.
const META_LABEL: Readonly<Partial<Record<MetaField, string>>> = { blockedBy: 'blocked_by', dependsOn: 'depends_on' };

const fmtMeta = (task: WorkTask, fields: MetaField[]): string => {
  const parts = fields.flatMap((field) => {
    const entry = task[field];
    const empty = Array.isArray(entry) ? entry.length === 0 : !entry;
    return empty ? [] : [`${META_LABEL[field] ?? field}: ${Array.isArray(entry) ? entry.join(', ') : entry}`];
  });
  return parts.length === 0 ? '' : ` _(${parts.join(' · ')})_`;
};

const issueLink = (task: WorkTask): string => {
  const label = issueLabel(task.issue);
  return label ? ` ↗ [${label}](${task.issue})` : '';
};

const taskLine = (task: WorkTask, fields: MetaField[]): string =>
  `- ${taskLink(task)} **${task.title}**${issueLink(task)}${fmtMeta(task, fields)}`;

const groupByProject = (tasks: WorkTask[]): [string, WorkTask[]][] =>
  [...Map.groupBy(tasks, (task) => task.project).entries()].sort(([a], [b]) => a.localeCompare(b));

const sectionBody = (lines: string[]): string => (lines.length === 0 ? '_(none)_' : lines.join('\n'));

// Every stale task already has its full line under Active or Blocked, so this section is only
// an index of ids with their last-update date, oldest first.
const renderStale = (tasks: WorkTask[]): string =>
  sectionBody(
    groupByProject(tasks).map(
      ([project, list]) =>
        `- **${project}**: ${list
          .toSorted((left, right) => left.updated.localeCompare(right.updated))
          .map((task) => `${task.id} (${task.updated.slice(5)})`)
          .join(' · ')}`
    )
  );

const renderActive = (tasks: WorkTask[]): string => {
  if (tasks.length === 0) return '_(none)_';
  return groupByProject(tasks)
    .map(([project, list]) => {
      const lines = list.map((t) => taskLine(t, ['priority', 'status', 'due']));
      return `### ${project}\n${lines.join('\n')}`;
    })
    .join('\n\n');
};

/** Pure formatter — assemble final markdown from sections + goals block. */
export const formatDashboard = (
  sections: DashboardSections,
  goalsBlock: string,
  malformed: readonly string[] = []
): string => {
  const header = `> Tasks hub — auto-generated by ${agentDisplayName()} from task frontmatter on every mutation. Do not edit this file directly: tasks change via the task tools, goals via the goals skill.\n> Last updated: ${todayDate()}\n`;

  // Unparseable files are absent from every section below, so without this
  // banner a broken task reads as a deleted one.
  const malformedBlock = malformed.length
    ? `\n> [!warning] ${malformed.length} task file${malformed.length === 1 ? '' : 's'} could not be parsed and ${malformed.length === 1 ? 'is' : 'are'} missing from the sections below. Frontmatter must open with \`---\` on line 1.\n${malformed.map((path) => `> - \`${basename(path)}\``).join('\n')}\n`
    : '';

  const blockedBody = sectionBody(
    sections.blocked.map((t) => taskLine(t, ['project', 'priority', 'blockedBy', 'dependsOn']))
  );
  const overdueBody = sectionBody(sections.overdue.map((t) => taskLine(t, ['project', 'priority', 'due', 'status'])));
  const closedBody = sectionBody(sections.closedRecent.map((t) => taskLine(t, ['project', 'status', 'closed'])));

  return [
    header,
    malformedBlock,
    goalsBlock.trim(),
    `## Active (${sections.active.length})\n\n${renderActive(sections.active)}\n`,
    `## Blocked (${sections.blocked.length})\n\n${blockedBody}\n`,
    `## Overdue (${sections.overdue.length})\n\n${overdueBody}\n`,
    `## Stale (${sections.stale.length})\n\n${renderStale(sections.stale)}\n`,
    `## Recently Closed (${sections.closedRecent.length})\n\n${closedBody}\n`
  ].join('\n');
};

// ── Goals-block preservation ──────────────────────────────────────────
// The goals block is written by the goals skill's playbooks, never
// edited by hand. The dashboard never touches it — extract from existing
// file, re-emit verbatim. Empty default is written on first run.

const GOALS_MARKER_START = '<!-- GOALS:START -->';
const GOALS_MARKER_END = '<!-- GOALS:END -->';

const EMPTY_GOALS_BLOCK = `${GOALS_MARKER_START}
## Daily Goals

_No daily goals set yet — run \`goals day\` to set today's._

## Weekly Goals

_No weekly goals set yet — run \`goals week\` to set them._

## Monthly Goals

_No monthly goals set yet — run \`goals month\`._

## Yearly Goals

_No yearly goals set yet — run \`goals year\` to plan the year by quarters._
${GOALS_MARKER_END}`;

const extractGoalsBlock = (existing: string): string => {
  const start = existing.indexOf(GOALS_MARKER_START);
  const end = existing.indexOf(GOALS_MARKER_END);
  if (start === -1 || end === -1 || end < start) return EMPTY_GOALS_BLOCK;
  return existing.slice(start, end + GOALS_MARKER_END.length);
};

// ── Write ────────────────────────────────────────────────────────────

export interface DashboardCounts {
  active: number;
  blocked: number;
  overdue: number;
  stale: number;
  closedRecent: number;
}

const sectionCounts = (sections: DashboardSections): DashboardCounts => ({
  active: sections.active.length,
  blocked: sections.blocked.length,
  overdue: sections.overdue.length,
  stale: sections.stale.length,
  closedRecent: sections.closedRecent.length
});

/** Rebuild and write projects/TASKS.md from the work model. Preserves the goals block. */
export const writeDashboard = (work: Work): DashboardCounts => {
  const tasksFile = join(FOLDERS.PROJECTS, 'TASKS.md');
  let existing = '';
  try {
    existing = readText(tasksFile);
  } catch {
    // first run — no existing file, use empty goals scaffold
  }
  const goalsBlock = extractGoalsBlock(existing);

  const sections = buildSections(work, todayDate());
  writeFileSync(tasksFile, formatDashboard(sections, goalsBlock, work.malformed));

  return sectionCounts(sections);
};

/**
 * The two derived views always regenerate together: TASKS.md (this module)
 * and the Agent OS dashboard at <HOME>/dashboard.html (status/html). The HTML
 * rebuild is fire-and-forget and coalesced — requests landing while one is
 * in flight keep only the latest model, and a single follow-up rebuild writes
 * it once the in-flight one finishes.
 */
let htmlInFlight = false;
let pendingWork: Work | null = null;

const rebuildHtmlSafe = (work: Work): void => {
  if (htmlInFlight) {
    pendingWork = work;
    return;
  }
  htmlInFlight = true;
  void import('@/status/html')
    .then(({ writeDashboardHtml }) => writeDashboardHtml(work))
    .catch(() => {
      // best-effort — TASKS.md is already written; the HTML view catches up
      // on the next mutation or explicit dashboard call
    })
    .finally(() => {
      htmlInFlight = false;
      const next = pendingWork;
      pendingWork = null;
      if (next) {
        rebuildHtmlSafe(next);
      }
    });
};

/**
 * Best-effort dashboard rebuild for call sites that shouldn't fail when the
 * dashboard write hiccups (sandbox denial, transient FS error). Logs but
 * never throws — the calling mutation is the source of truth, the dashboard
 * is a derived view. Also refreshes the Agent OS dashboard (async,
 * coalesced) so both views stay in lockstep.
 *
 * When called from inside `withDashboardBatch(...)`, defers the actual write
 * until the outer scope exits — so a multi-mutation flow like `applyResolution`
 * does one rebuild instead of one per mutation (5-10x reduction).
 */
let batchDepth = 0;
let pendingWrite = false;

export const writeDashboardSafe = (): DashboardCounts | null => {
  if (batchDepth > 0) {
    pendingWrite = true;
    return null;
  }
  try {
    const work = buildWork();
    const counts = writeDashboard(work);
    rebuildHtmlSafe(work);
    return counts;
  } catch {
    return null;
  }
};

/** Defer dashboard rebuilds inside `fn`; flush a single write after it returns. */
export const withDashboardBatch = <T>(fn: () => T): T => {
  batchDepth++;
  try {
    return fn();
  } finally {
    batchDepth--;
    if (batchDepth === 0 && pendingWrite) {
      pendingWrite = false;
      try {
        const work = buildWork();
        writeDashboard(work);
        rebuildHtmlSafe(work);
      } catch {
        // best-effort — caller has already succeeded
      }
    }
  }
};
